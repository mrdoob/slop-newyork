// tools/hk/build-coastline.mjs — writes js/hk-coastline.js from tools/data/hk/coastline.json
//
// The coastline is **real**: the Hong Kong Lands Department terrestrial boundary (as republished in
// aknopla/hk-terrestrial-geojson, hk_terrestrial_2m.geojson), simplified with Ramer–Douglas–Peucker and
// projected into the simulation's world frame (x = east, z = south, 1 unit = 1 m, origin Statue Square).
//
//   node tools/hk/build-coastline.mjs
//
// Regenerating from the raw GeoJSON (not committed — it is 1.7 MB) is a two-line change in `tools/data/hk/`:
//   curl -LO https://github.com/aknopla/hk-terrestrial-geojson/raw/main/hk_terrestrial_2m.geojson
// then re-run tools/hk/prepare-coastline.mjs (see that file).
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const SRC = fileURLToPath(new URL('../data/hk/coastline.json', import.meta.url));
const OUT = process.argv[2] || fileURLToPath(new URL('../../js/hk-coastline.js', import.meta.url));

const data = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const flat = (rings) => rings.map((ring) => ring.flatMap(([x, z]) => [x, z]));
const COAST = {
  version: 2,
  source: data.source,
  // land      玩樂範圍內的海岸線（~12 m 精度，中環／尖沙咀／旺角一帶）
  // territory 全港其餘陸地（~150 m 精度：新界、大嶼山、西貢、離島）—— 地圖縮到全港時靠它成形
  land: flat(data.land),
  territory: flat(data.territory)
};
const json = JSON.stringify(COAST);
const header = `// js/hk-coastline.js — GENERATED by tools/hk/build-coastline.mjs, do not edit by hand.
// 真實的海岸線（地政總署陸地邊界），已經簡化並投影到遊戲的世界座標：
//   1 unit = 1 m、x = 東、z = 南（北 = −z），原點 = 中環皇后像廣場。
//   land       玩樂範圍的海岸線（~12 m 精度）
//   territory  新界與離島的輪廓（~150 m 精度）
// 每個 ring 都是 flat [x0, z0, x1, z1, …]。
`;
fs.writeFileSync(OUT, `${header}export const COAST = ${json};\n`);
const kb = (fs.statSync(OUT).size / 1024).toFixed(0);
console.log(`[coastline] ${COAST.land.length} land + ${COAST.territory.length} territory rings → ${OUT} (${kb} kB)`);
